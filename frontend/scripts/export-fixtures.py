"""Export the selected synthetic demo, reading source archives without mutation.

Regeneration only; the standalone frontend needs Node, not these Python modules.
No database credentials, private paths, labels, or live network calls are exported.
"""
import argparse
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import sqlite3
import sys

sys.dont_write_bytecode = True
parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, required=True)
args = parser.parse_args()
root = args.source.resolve()
sys.path[:0] = [str(root/'graph-viewer'), str(root/'rag-service'), str(root/'rule-service')]
from retrieval import Index
from evidence import build_context
from evidence_lookup import EvidenceRepository
from reports import generate_report
from report_verification import verify_report
from analysis_history import validate_capture

archive = root/'data/history/analysis.sqlite3'
with sqlite3.connect(archive.as_uri()+'?mode=ro', uri=True) as connection:
    captures = [json.loads(row[0])['capture'] for row in connection.execute(
        "SELECT body FROM analysis_history WHERE tx_id = ?", ('TX-000619283',))]
initial = deepcopy(next(c for c in captures if len(c['payload']['graph']['edges']) == 69))
expanded = deepcopy(next(c for c in captures if len(c['payload']['graph']['edges']) == 72 and c['review']))
repository = EvidenceRepository(Index(root/'data/rag/index.json'))
index = repository.index_for(expanded['review']['context']['corpusSha256'])
payload = initial['payload']
context = build_context(index, payload['graph'], payload['ruleResult'])
report = generate_report(context, mode='template')
verification = verify_report(repository, payload['graph'], payload['ruleResult'], report)
assert verification['valid'], verification['errors']
initial['review'] = {'context': context, 'report': report, 'verification': verification,
    'focus': deepcopy(expanded['review']['focus']),
    'source': {**expanded['review']['source'], 'graphSha256': context['graphSha256'],
               'queriedAt': payload['source']['queriedAt']}}
initial['citations'] = {c['chunkId']: repository.citation(c['chunkId'], context['corpusSha256'])
                       for c in report['citations']}
for capture in [initial, expanded]:
    validate_capture(capture)
    assert capture['payload']['target']['txId'] == 'TX-000619283'
    assert capture['payload']['accountExpansion']['datasetSha256'] == expanded['payload']['accountExpansion']['datasetSha256']
output = Path(__file__).resolve().parents[1]/'fixtures'
for name, capture in [('initial', initial), ('expanded', expanded)]:
    raw = json.dumps(capture, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()
    (output/(name+'.json')).write_bytes(raw)
provenance = {'schemaVersion': '1.0', 'syntheticData': True,
    'targetTxId': 'TX-000619283', 'windowDays': 7, 'hops': 2,
    'datasetSha256': expanded['payload']['accountExpansion']['datasetSha256'],
    'source': 'Existing synthetic analysis archive; initial review generated by existing template engine with pinned corpus',
    'counts': {'initial': 69, 'expanded': 72, 'readRows': 4, 'added': 3, 'duplicates': 1},
    'fixtureSha256': {n: hashlib.sha256((output/(n+'.json')).read_bytes()).hexdigest() for n in ['initial','expanded']}}
(output/'provenance.json').write_text(json.dumps(provenance, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
print(json.dumps(provenance, ensure_ascii=False, indent=2))
